"""Cost model: what it costs to onboard a vendor (or a customer's set of vendors), from the token usage we
measured in the benchmark runs. Prints a markdown report (COSTS.md).

Assumptions are explicit below; change them and re-run. Prices: Claude Opus 5.5 list prices per 1M tokens.
"""
MODELS = {   # $ per 1M tokens (list prices; 1h cache write = 2x input)
    "claude-opus-5-5":   {"input": 4.00, "output": 20.00, "cache_read": 0.20, "cache_write_1h": 8.00},
    "claude-sonnet-5-5": {"input": 2.00, "output": 10.00, "cache_read": 0.10, "cache_write_1h": 4.00},
}
PRICE = dict(MODELS["claude-opus-5-5"])

# Tool-using agent sessions re-send their growing context each turn; with prompt caching most of it is a
# cache read. Measured totals are session token counts, split with these shares (estimate):
AGENT_MIX_CACHED = {"cache_read": 0.85, "input": 0.10, "output": 0.05}
AGENT_MIX_UNCACHED = {"cache_read": 0.0, "input": 0.95, "output": 0.05}

# ---- measured in this repo's benchmark (bench/RESULTS.md) ----
FORMATS_PER_VENDOR = 81 / 15            # parser formats per vendor in the 15-vendor benchmark (incl. fallbacks)
GROUPING_TOKENS_PER_VENDOR = 221_104 / 12   # learner with code tools: 12 new vendors + 15 suspects in one session
PARSER_TOKENS_TOTAL = 297_619 + 235_520 + 278_245 + 140_387   # 3 parser groups + fallback agent, 15 vendors
PARSER_TOKENS_PER_VENDOR = PARSER_TOKENS_TOTAL / 15
M1 = {"calls": 1.25, "prompt": 2_282, "answer": 861, "schema": 63_151}   # per format, measured (20 formats)
AGENT_MAPPING_TOKENS_PER_FORMAT = 21_000          # tool-using mapping agent (earlier runs)
REVIEW_ONESHOT = {"prompt": 4_000, "answer": 1_000}   # optional reviewer call per format, schema cached


def dollars(tokens_by_kind):
    return sum(tokens_by_kind.get(k, 0) * PRICE[k] for k in PRICE) / 1e6


def agent_cost(tokens, mix):
    return dollars({k: tokens * v for k, v in mix.items()})


def m1_per_format():
    return dollars({"cache_read": M1["schema"] * M1["calls"], "input": M1["prompt"], "output": M1["answer"]})


def review_per_format():
    return dollars({"cache_read": M1["schema"], "input": REVIEW_ONESHOT["prompt"], "output": REVIEW_ONESHOT["answer"]})


def cache_write():
    return dollars({"cache_write_1h": M1["schema"]})


def report():
    rows = []
    f = FORMATS_PER_VENDOR
    g_lo, g_hi = agent_cost(GROUPING_TOKENS_PER_VENDOR, AGENT_MIX_CACHED), agent_cost(GROUPING_TOKENS_PER_VENDOR, AGENT_MIX_UNCACHED)
    p_lo, p_hi = agent_cost(PARSER_TOKENS_PER_VENDOR, AGENT_MIX_CACHED), agent_cost(PARSER_TOKENS_PER_VENDOR, AGENT_MIX_UNCACHED)
    m_bulk = m1_per_format() * f
    m_alone = m_bulk + cache_write()
    r = review_per_format() * f
    a_lo = agent_cost(AGENT_MAPPING_TOKENS_PER_FORMAT * f, AGENT_MIX_CACHED)
    a_hi = agent_cost(AGENT_MAPPING_TOKENS_PER_FORMAT * f, AGENT_MIX_UNCACHED)
    rows.append(("Grouping rules (learner agent, code tools)", f"{GROUPING_TOKENS_PER_VENDOR/1e3:.0f}k", f"${g_lo:.2f} – ${g_hi:.2f}"))
    rows.append(("Parsers (parser agent, incl. fallback parser)", f"{PARSER_TOKENS_PER_VENDOR/1e3:.0f}k", f"${p_lo:.2f} – ${p_hi:.2f}"))
    rows.append((f"OCSF mapping, M1 ({f:.1f} formats x {M1['calls']} calls, schema cached)",
                 f"{(M1['prompt'] + M1['answer']) * f / 1e3:.0f}k + cached schema", f"${m_bulk:.2f} – ${m_alone:.2f}"))
    rows.append(("Optional AI review (one call per format)", f"{sum(REVIEW_ONESHOT.values()) * f / 1e3:.0f}k + cached schema", f"${r:.2f}"))
    lo = g_lo + p_lo + m_bulk
    hi = g_hi + p_hi + m_alone + r
    out = ["# Cost model (generated by bench/cost_model.py)", "",
           "Prices: Claude Opus 5.5 per 1M tokens: input $4, output $20, cache read $0.20, cache write (1h) $8.",
           "Token figures are measured in this repo's benchmark runs (bench/RESULTS.md); agent sessions are split",
           "into cache reads / fresh input / output with an assumed mix (85/10/5 with prompt caching, 0/95/5 without).",
           "", "## One-time cost to onboard one vendor (avg %.1f log formats per vendor)" % f, "",
           "| Step | Tokens per vendor | Cost per vendor |", "|---|---|---|"]
    out += [f"| {a} | {b} | {c} |" for a, b, c in rows]
    out += [f"| **Total** | | **${lo:.2f} – ${hi:.2f}** |", "",
            f"For comparison, mapping with the tool-using agent instead of M1: ${a_lo:.2f} – ${a_hi:.2f} per vendor.", "",
            "## What a customer pays", "",
            "- **Known vendors/formats: $0 in LLM cost.** Grouping, parsing and mapping run as compiled rules in Logstash.",
            f"- **New vendor:** ${lo:.2f} – ${hi:.2f} once (all its formats).",
            f"- **New message type of a known vendor (drift):** about ${agent_cost(PARSER_TOKENS_PER_VENDOR / f, AGENT_MIX_CACHED) + m1_per_format():.2f} – "
            f"${agent_cost(PARSER_TOKENS_PER_VENDOR / f, AGENT_MIX_UNCACHED) + m1_per_format() + review_per_format():.2f} (one parser + one mapping).",
            "- **Example:** a customer sending 10 vendors we have never seen: "
            f"${10 * lo:.0f} – ${10 * hi:.0f} once; a customer whose vendors are all known: $0.", "",
            "Not included: compute for Logstash/Kafka (runs the compiled pipeline; scales with event volume, not with",
            "LLM usage), the embedding model (not needed for M1), and engineering time for human review gates.", "",
            "Levers: running the parser/learner agents on a cheaper model (e.g. Sonnet) for routine formats; batching",
            "many formats inside one 1-hour cache window (the schema cache write is paid once per window); skipping the",
            "optional review for vendors whose mappings validate cleanly."]
    return "\n".join(out)


if __name__ == "__main__":
    import sys
    parts = []
    for model in MODELS:
        PRICE.clear(); PRICE.update(MODELS[model])
        parts.append(report().replace("# Cost model (generated by bench/cost_model.py)", f"# Cost model: {model}")
                     .replace("Prices: Claude Opus 5.5 per 1M tokens: input $4, output $20, cache read $0.20, cache write (1h) $8.",
                              "Prices per 1M tokens: " + ", ".join(f"{k} ${v}" for k, v in MODELS[model].items()) + "."))
    txt = ("Measured: Sonnet 5.5 matches Opus 5.5 on the OCSF mapper (precision 89.5% vs 89.6%, recall 72.6% vs "
           "73.9%, same class on 19/20 formats) and on the parser agent (SonicWall from scratch: 121/121 held-out "
           "lines parsed, Logstash-identical). See bench/RESULTS.md.\n\n" + "\n\n".join(parts))
    print(txt)
    if len(sys.argv) > 1:
        open(sys.argv[1], "w").write(txt + "\n")
